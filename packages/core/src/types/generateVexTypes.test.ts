describe("generateVexTypes - select option alias naming", () => {
  it("does not collide when two collections share a select field key", () => {
    const config = defineServerConfig({ config: defineConfig({
      collections: [
        defineCollection({
          slug: "articles",
          interfaceName: "Article",
          fields: {
            status: select({
              required: true,
              options: [{ label: "Draft", value: "draft" }],
            }),
          },
        }),
        defineCollection({
          slug: "changelog",
          interfaceName: "ChangelogEntry",
          fields: {
            status: select({
              required: true,
              options: [{ label: "Draft", value: "draft" }],
            }),
          },
        }),
      ],
    }) })
    const output = generateVexTypes({ config });
    // One alias per collection, each named for its own interface. Before this was
    // qualified, both emitted `type StatusOption` and the file had a duplicate
    // identifier — a TS error in generated code the author cannot edit.
    expect(output).toContain("type ArticleStatusOption");
    expect(output).toContain("type ChangelogEntryStatusOption");
    expect(output).not.toContain("type StatusOption");
    expect(output).toContain("status: ArticleStatusOption[]");
    expect(output).toContain("status: ChangelogEntryStatusOption[]");
  });

  it("honours optionInterfaceName over the qualified default", () => {
    const config = defineServerConfig({ config: defineConfig({
      collections: [
        defineCollection({
          slug: "articles",
          interfaceName: "Article",
          fields: {
            status: select({
              required: true,
              optionInterfaceName: "EditorialStatus",
              options: [{ label: "Draft", value: "draft" }],
            }),
          },
        }),
      ],
    }) })
    const output = generateVexTypes({ config });
    expect(output).toContain("type EditorialStatus");
    expect(output).toContain("status: EditorialStatus[]");
    expect(output).not.toContain("ArticleStatusOption");
  });
});

