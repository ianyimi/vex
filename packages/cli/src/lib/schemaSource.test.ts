import { describe, expect, it } from "vitest";

import { findSchemaCollisions, readGeneratedTables, readSchemaEntries } from "./schemaSource";

/** Generated `vex.schema.ts` text, in the generator's own (unformatted) layout. */
const GENERATED = `// ⚠️ AUTO-GENERATED BY VEX CMS — DO NOT EDIT ⚠️
import { defineTable } from "convex/server"
import { v } from "convex/values"

export const posts = defineTable({
\ttitle: v.string(),
\tslug: v.string(),
\tsubtitle: v.optional(v.nullable(v.string())),
\tviews: v.optional(v.number()),
})
\t.index("by_slug", ["slug"])

/**
 * VEX VERSIONS — immutable history
 **/

export const vex_versions = defineTable({
  collection: v.string(),
})
  .index("by_collection", ["collection"])
`;

const collide = (schemaSource: string) =>
  findSchemaCollisions({
    entries: readSchemaEntries({ source: schemaSource })!,
    generatedTables: readGeneratedTables({ source: GENERATED }),
  });

describe("readSchemaEntries", () => {
  it("reads every key form and ignores keys inside comments and strings", () => {
    const entries = readSchemaEntries({
      source: `
        import { defineSchema, defineTable } from "convex/server";
        export default defineSchema({
          posts,
          // legacy: defineTable({}),
          vex_versions: vex_versions,
          "quoted-name": defineTable({ note: v.string() /* tags: */ }),
          [TABLE_SLUG_ACCOUNTS]: defineTable({ userId: v.string() }),
          ...extraTables,
        });
      `,
    });
    expect(entries).toEqual([
      { kind: "shorthand", name: "posts" },
      { kind: "property", name: "vex_versions", value: "vex_versions" },
      { kind: "property", name: "quoted-name", value: 'defineTable({note:v.string()})' },
      { kind: "computed", key: "TABLE_SLUG_ACCOUNTS", value: "defineTable({userId:v.string()})" },
      { kind: "opaque" },
    ]);
  });

  it("returns undefined when defineSchema has no object literal", () => {
    expect(readSchemaEntries({ source: "export default defineSchema(tables);" })).toBeUndefined();
  });
});

describe("findSchemaCollisions", () => {
  it("stays quiet for a hand-written copy that differs only in formatting", () => {
    expect(
      collide(`export default defineSchema({
        posts: defineTable({
          slug: v.string(),
          views: v.optional(v.float64()),
          title: v.string(),
          subtitle: v.optional(v.union(v.string(), v.null())),
        }).index('by_slug', ['slug',]),
      })`),
    ).toEqual([]);
  });

  it("reports how a drifted hand-written table differs from the generated one", () => {
    expect(
      collide(`export default defineSchema({
        posts: defineTable({
          title: v.string(),
          slug: v.optional(v.string()),
          legacyFlag: v.boolean(),
        })
          .index("by_slug", ["slug", "title"])
          .index("by_legacyFlag", ["legacyFlag"]),
      })`),
    ).toEqual([
      {
        kind: "table",
        table: "posts",
        diff: {
          fieldsOnlyInSchema: ["legacyFlag"],
          fieldsOnlyGenerated: ["subtitle", "views"],
          fieldsChanged: ["slug"],
          indexesOnlyInSchema: ["by_legacyFlag"],
          indexesOnlyGenerated: [],
          indexesChanged: ["by_slug"],
        },
      },
    ]);
  });

  it("never reports the generated import itself", () => {
    expect(collide("export default defineSchema({ posts, vex_versions: vex_versions })")).toEqual([]);
  });

  it("reports an index chained onto the import that reuses a generated index name", () => {
    expect(
      collide(`export default defineSchema({
        posts: posts.index("by_slug", ["slug"]).index("by_title", ["title"]),
      })`),
    ).toEqual([{ kind: "index", table: "posts", indexes: ["by_slug"] }]);
    expect(collide(`export default defineSchema({ posts: posts.index("by_title", ["title"]) })`)).toEqual([]);
  });

  it("reports a hand-written value it can't compare", () => {
    expect(collide("export default defineSchema({ posts: postsTable })")).toEqual([
      { kind: "table", table: "posts", diff: undefined },
    ]);
  });

  it("never reports computed keys or tables the generated schema doesn't have", () => {
    expect(
      collide(`export default defineSchema({
        ["posts"]: defineTable({ other: v.string() }),
        comments: defineTable({ body: v.string() }),
      })`),
    ).toEqual([]);
  });
});
